package Arrays;

public class ArrayBasics {
    public static void main(String[] args) {
        int [] arr = {2,4,6,8,10};    // Declaration/ Initialization of Array!!

        // int [] arr = new int [5];     // Another way of Declaration / Initialization of Array!!

        System.out.println(arr[2]);
        arr[2] = 12;
        System.out.println(arr[2]);
    }
}
